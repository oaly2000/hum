import type { Plugin } from "vite";

import {
  BUILD_VIRTUAL_ID,
  ROUTES_VIRTUAL_ID,
  type HumContext,
  virtualModule,
} from "../shared.js";

/**
 * Exposes the build Hum runs from as a virtual module.
 *
 * The module calls `defineBuild`, which is how the runtime learns its routes,
 * its islands and its client assets: nothing reaches it through configuration
 * any more, so the same code boots the dev server and the deployed bundle. The
 * assets come from the plugin context, which the build plugin fills in once the
 * client pass has written them — there is no manifest file for the app to read
 * at startup, and the runtime never touches the file system.
 */
export function humBuildInput(ctx: HumContext): Plugin {
  return virtualModule(
    "hum:build-input",
    BUILD_VIRTUAL_ID,
    () => buildModuleSource(ctx),
  );
}

/** Source of the `virtual:hum/build` module. */
export function buildModuleSource(ctx: HumContext): string {
  // Development has no client build, and the modules are served straight from
  // Vite, so `prod` stays `null` there.
  const prod = ctx.prod ?? null;
  const config = {
    routesDir: ctx.options.routesDir,
    islandsDir: ctx.options.islandsDir,
    basePath: ctx.options.basePath,
    dev: prod === null,
  };

  return `// Generated by @humjs/vite-plugin (${BUILD_VIRTUAL_ID}). Do not edit.
import { defineBuild } from "@humjs/core";
import { manifest } from "${ROUTES_VIRTUAL_ID}";

export const config = ${JSON.stringify(config)};

export const build = defineBuild({
  origin: ${JSON.stringify(ctx.options.prerenderOrigin)},
  pages: ${JSON.stringify(ctx.pages ?? {})},
  routes: manifest.routes,
  islands: manifest.islands,
  prod: ${JSON.stringify(prod)},
});
`;
}
