import { globPatterns } from "@humjs/core/routing";
import type { Plugin } from "vite";
import { STYLE_QUERY, STYLES_ID } from "./styles.js";

import {
  globCall,
  CLIENT_SLICE_QUERY,
  clientMetadataGlob,
  type DeclaredClientDefinition,
  ROUTES_VIRTUAL_ID,
  type HumContext,
  type ResolvedHumOptions,
  virtualModule,
} from "../shared.js";

/**
 * Exposes the route and island manifest as a virtual module built on
 * `import.meta.glob`.
 *
 * Discovery therefore happens inside the bundler's module graph instead of a
 * runtime directory scan: Vite knows the file list while it transforms this
 * module, the same rules apply to development and to a production build, and
 * the emitted server bundle carries lazy imports rather than a serialized
 * route table with build machine paths. Adding or removing a route file
 * invalidates this module the way it invalidates any other glob owner.
 *
 * Route names follow `@humjs/core/routing`; island metadata comes only from
 * explicit declarations analyzed by the bundler.
 */
export function humRoutes(ctx: HumContext): Plugin {
  return virtualModule(
    "hum:routes",
    ROUTES_VIRTUAL_ID,
    () => routesModuleSource(ctx.options, ctx.prod
      ? [...ctx.clientDeclarations?.values() ?? []].flat()
      : undefined),
  );
}

/** Source of the `virtual:hum/routes` module. */
export function routesModuleSource(options: ResolvedHumOptions, declarations?: DeclaredClientDefinition[]): string {
  const patterns = globPatterns(options);
  // The client pass already enumerated and analyzed every source through Vite.
  // Reuse that metadata in production instead of emitting a wrapper per file.
  const production = declarations !== undefined;
  const declarationSource = production
    ? `const declarations = [${declarations.map(entry =>
      `{...${JSON.stringify({ ...entry, clientFile: entry.file + "?" + CLIENT_SLICE_QUERY })},load:()=>import(${JSON.stringify("/" + entry.file)})}`
    ).join(",")}];`
    : `const declaredModules = ${clientMetadataGlob(options)};
const declarations = Object.values(declaredModules).flat();`;

  return `// Generated by @humjs/vite-plugin (${ROUTES_VIRTUAL_ID}). Do not edit.
import { specsFromGlob } from "@humjs/core/routing";
import { h, Fragment } from "preact";
${production ? `import styles from ${JSON.stringify(STYLES_ID)};` : ""}

const sources = ${globCall(patterns.routes)};
${production ? "" : `const styleModules = import.meta.glob(${JSON.stringify(patterns.routes)}, { query: "?${STYLE_QUERY}", import: "default" });`}
const routeModules = Object.fromEntries(Object.entries(sources).map(([file, load]) => [file, async () => {
  const mod = await load();
  ${production ? 'const getStyles = () => styles[file.slice(1)] ?? [];' : "const getStyles = await styleModules[file]();"}
  return { ...mod, head: (props) => h(Fragment, null,
    typeof mod.head === "function" ? mod.head(props) : mod.head,
    getStyles().map(href => h("link", { rel: "stylesheet", href }))) };
}]));
${declarationSource}

export const manifest = specsFromGlob({
  routesDir: ${JSON.stringify(options.routesDir)},
  routeModules,
  declaredIslands: declarations.filter((entry) => entry.kind === "island"),
  factories: declarations.filter((entry) => entry.kind === "factory"),
});

export const routes = manifest.routes;
export const islands = manifest.islands;
`;
}
