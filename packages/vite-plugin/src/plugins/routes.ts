import { globPatterns } from "@humjs/core/routing";
import type { Plugin } from "vite";

import {
  globCall,
  ROUTES_VIRTUAL_ID,
  type HumContext,
  type ResolvedHumOptions,
  virtualModule,
} from "../shared.js";

/**
 * Exposes the route and island manifest as a virtual module built on
 * `import.meta.glob`.
 *
 * Discovery therefore happens inside the bundler's module graph instead of a
 * runtime directory scan: Vite knows the file list while it transforms this
 * module, the same rules apply to development and to a production build, and
 * the emitted server bundle carries lazy imports rather than a serialized
 * route table with build machine paths. Adding or removing a route file
 * invalidates this module the way it invalidates any other glob owner.
 *
 * The file naming rules themselves live in `@humjs/core/routing`, so this
 * module and `crawlProject` (the file system fallback for callers without a
 * bundler) agree on what a route or island file is.
 */
export function humRoutes(ctx: HumContext): Plugin {
  return virtualModule(
    "hum:routes",
    ROUTES_VIRTUAL_ID,
    () => routesModuleSource(ctx.options),
  );
}

/** Source of the `virtual:hum/routes` module. */
export function routesModuleSource(options: ResolvedHumOptions): string {
  const patterns = globPatterns(options);

  return `// Generated by @humjs/vite-plugin (${ROUTES_VIRTUAL_ID}). Do not edit.
import { specsFromGlob } from "@humjs/core/routing";

const routeModules = ${globCall(patterns.routes)};
const islandModules = ${globCall(patterns.islands)};
const localIslandModules = ${globCall(patterns.localIslands)};

export const manifest = specsFromGlob({
  routesDir: ${JSON.stringify(options.routesDir)},
  islandsDir: ${JSON.stringify(options.islandsDir)},
  routeModules,
  islandModules,
  localIslandModules,
});

export const routes = manifest.routes;
export const islands = manifest.islands;
`;
}
