import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

import { globPatterns } from "@humjs/core/routing";
import type { Plugin } from "vite";

import type { HumContext } from "../shared.js";
import {
  BUILD_VIRTUAL_ID,
  CLIENT_RUNTIME_ENTRY,
  CORE_RUNTIME_ID,
  GENERATED_DIR,
  globCall,
  ISLANDS_ENTRY,
  SERVER_ENTRY,
  SERVER_ENTRY_FILE,
} from "../shared.js";

/**
 * Keeps the client runtime in the production bundle.
 *
 * In development the client runtime — including the optional user client entry
 * — is served through the `hum:client-entry` virtual module, and every island
 * file is served straight from Vite, so no extra entry is needed: `BuildCache`
 * points the boot script at `/islands/Foo.tsx` and Vite transforms that request
 * on the fly.
 */
export function humIslands(): Plugin {
  return {
    name: "hum:islands",

    // The runtime's entry exports are consumed from outside the bundle by the
    // server-inlined boot script, which is the tree-shaking constraint described
    // in `@humjs/core/runtime/client`. The runtime modules below are marked
    // side-effectful so Rolldown (Vite 8) cannot drop the module the entry
    // re-exports from, which would leave the entry chunk without `boot`.
    transform(code, id) {
      if (
        id.includes(CORE_RUNTIME_ID) ||
        id.includes("/runtime/client/")
      ) {
        return { code, moduleSideEffects: "no-treeshake" };
      }
      return null;
    },
  };
}

/**
 * Writes the entry files the production build needs into `.hum/`. The client
 * build bundles the runtime once, plus one chunk per island that the islands
 * entry makes the bundler emit; the server build gets an entry that boots a
 * real Node server from the build the bundler produced while it ran.
 */
export async function writeBuildEntries(ctx: HumContext): Promise<void> {
  const dir = join(ctx.options.root, GENERATED_DIR);
  await mkdir(dir, { recursive: true });
  const userServer = resolve(ctx.options.root, SERVER_ENTRY_FILE);

  // The runtime entry imports the optional user client entry first, so its
  // global styles (e.g. TailwindCSS) become part of the runtime chunk and flow
  // into the manifest's `entryAssets` in production.
  const userEntry = resolve(ctx.options.root, ctx.options.clientEntry);
  const userImport = existsSync(userEntry)
    ? `import ${JSON.stringify(userEntry)};\n`
    : "";
  // The boot script in the server-rendered HTML imports `boot` from this entry
  // and calls it, but that call lives outside the bundle, so the entry has to
  // keep the runtime's exports alive itself — see the tree-shaking note in
  // `@humjs/core/runtime/client`. Importing the bindings locally and
  // re-exporting them, plus the `globalThis` reference, keeps the runtime (and
  // its partial navigation side effects) in the emitted chunk.
  await writeFile(
    join(ctx.options.root, CLIENT_RUNTIME_ENTRY),
    userImport +
      `import { boot, revive, applyPartials, hum_island_registry } from ${
        JSON.stringify(CORE_RUNTIME_ID)
      };\n` +
      `export { boot, revive, applyPartials, hum_island_registry };\n` +
      `globalThis.__humRuntime = { boot, revive, applyPartials };\n` +
      `void applyPartials;\n`,
    "utf8",
  );

  // Islands become one chunk each, discovered by the bundler instead of by a
  // directory scan. The exported object is what keeps the lazy imports: with
  // nothing importing this entry, tree-shaking would drop the glob result and
  // with it every island chunk. The browser never requests this module — it
  // loads the island chunks by URL from the server rendered markup.
  const patterns = globPatterns(ctx.options);
  await writeFile(
    join(ctx.options.root, ISLANDS_ENTRY),
    `// Generated by @humjs/vite-plugin (hum:islands). Do not edit.\n` +
      `export const islandModules = ${
        globCall([...patterns.islands, ...patterns.localIslands])
      };\n`,
    "utf8",
  );

  // Routes, islands and client assets all belong to the bundler: importing the
  // build module registers them with the runtime, so the entry carries no
  // serialized route table, no manifest and no path of the machine that built
  // it — the deployed bundle runs wherever it is started from.
  //
  // Whether the build serves itself is the project's own business, declared by
  // its entry file: `server.ts` default-exports the Hono instance that answers
  // requests, and exports `start(app)` only if the build should bind a port
  // itself. A deployment that calls `fetch` — a Worker, an edge runtime, a
  // test — omits `start` and imports the exported app instead.
  const entry = existsSync(userServer)
    ? projectEntry(ctx, userServer)
    : standaloneEntry(ctx);

  await writeFile(join(ctx.options.root, SERVER_ENTRY), entry, "utf8");
}

/**
 * Entry of a project that has a `server.ts`: the app it default-exports is
 * mounted, exported, and handed to its own `start` export if it has one.
 */
function projectEntry(ctx: HumContext, entryFile: string): string {
  return `// Generated by @humjs/vite-plugin. Do not edit.
import { mountHum } from "@humjs/core";
import ${JSON.stringify(BUILD_VIRTUAL_ID)};
import * as entry from ${JSON.stringify(entryFile.replace(/\\/g, "/"))};

const humConfig = {
  routesDir: ${JSON.stringify(ctx.options.routesDir)},
  islandsDir: ${JSON.stringify(ctx.options.islandsDir)},
  dev: false,
};

const app = entry.default;
await mountHum(app, humConfig);

${EXPORTED_APP}
${START_EXPORT}`;
}

/**
 * Entry of a project without a `server.ts`: there is no app and no `start` to
 * hand the build to, so it makes one and serves it on Node itself.
 */
function standaloneEntry(ctx: HumContext): string {
  return `// Generated by @humjs/vite-plugin. Do not edit.
import { createApp } from "@humjs/core";
import { serve } from "@hono/node-server";
import ${JSON.stringify(BUILD_VIRTUAL_ID)};

const humConfig = {
  routesDir: ${JSON.stringify(ctx.options.routesDir)},
  islandsDir: ${JSON.stringify(ctx.options.islandsDir)},
  dev: false,
};

const app = await createApp(humConfig);

${NODE_SERVING}`;
}

/**
 * The build's public interface.
 *
 * A Hono instance *is* its fetch handler, so exporting the app is enough for
 * anything that calls `fetch`: a Worker runtime, an edge runtime, a test. It is
 * what makes one build deployable anywhere, and it is why the framework never
 * needs to be told which platform it is building for.
 */
const EXPORTED_APP = `// The app is the build's export: whatever imports this module calls its fetch.
export default app;`;

/**
 * How the build starts itself, when the project's entry asked for it.
 *
 * Serving is the entry's business rather than the framework's: a deployment
 * that runs behind a platform calling `fetch` exports no `start` and never
 * binds a port, and it is the entry file — not a plugin option — that says so.
 */
const START_EXPORT = `// The entry's own \`start(app)\`, which is the build's entry point. Nothing
// binds a port here unless the project exported it.
if (typeof entry.start === "function") await entry.start(app);`;

/** Listener a project without an entry file gets. */
const NODE_SERVING = `// The Node adapter owns the listener.
const port = Number(process.env.PORT ?? 3000);
const hostname = process.env.HOST ?? "0.0.0.0";

serve(
  { fetch: app.fetch, port, hostname, overrideGlobalObjects: false },
  (info) => {
    console.log(\`hum: listening on http://localhost:\${info.port}\`);
  },
);
`;
