import { resolve } from "node:path";

import type { HumManifest, Logger } from "./types.js";

export interface HumConfig {
  /**
   * Project root. Defaults to `process.cwd()`.
   */
  root?: string;
  /** Routes directory, relative to the root. Defaults to `routes`. */
  routesDir?: string;
  /** Islands directory, relative to the root. Defaults to `islands`. */
  islandsDir?: string;
  /** Output directory of the production build. Defaults to `_hum`. */
  outDir?: string;
  /**
   * URL the production build output is served from. The build manifest carries
   * it, so it is normally read from there; the fallback is `/<outDir>`.
   */
  assetsBase?: string;
  /** Base path the app is served from. Defaults to `/`. */
  basePath?: string;
  /**
   * Run in development mode: modules are re-imported per request so edits show
   * up without a restart, and islands are served straight from Vite.
   * Defaults to `true` when no production manifest exists.
   */
  dev?: boolean;
  /**
   * Route and island modules generated by the bundler. The Vite plugin
   * generates this; when omitted, Hum discovers the files on disk (useful for
   * tests and programmatic use).
   */
  manifest?: HumManifest;
  logger?: Logger;
}

export interface ResolvedConfig {
  root: string;
  routesDir: string;
  islandsDir: string;
  outDir: string;
  assetsBase: string;
  basePath: string;
  dev: boolean;
  manifest: HumManifest;
  logger: Logger;
}

export const defaultLogger: Logger = {
  info: (...args) => console.log("hum:", ...args),
  warn: (...args) => console.warn("hum:", ...args),
  error: (...args) => console.error("hum:", ...args),
  debug: (...args) => {
    if (process.env.HUM_DEBUG) console.log("hum:", ...args);
  },
};

/**
 * Normalizes an absolute URL prefix: it always starts with `/` and never ends
 * with one, so callers can append `/<path>` unconditionally.
 */
function normalizeAssetsBase(value: string): string {
  const trimmed = value.trim().replace(/\\/g, "/");
  const withLeadingSlash = trimmed.startsWith("/") ? trimmed : `/${trimmed}`;
  return withLeadingSlash.replace(/\/+$/, "");
}

export function resolveConfig(config: HumConfig, manifest: HumManifest): ResolvedConfig {
  const root = resolve(config.root ?? process.cwd());
  let basePath = config.basePath ?? "/";
  if (basePath !== "/" && basePath.endsWith("/")) {
    basePath = basePath.slice(0, -1);
  }
  if (basePath === "/") basePath = "";

  const outDir = config.outDir ?? "_hum";

  return {
    root,
    routesDir: config.routesDir ?? "routes",
    islandsDir: config.islandsDir ?? "islands",
    outDir,
    assetsBase: normalizeAssetsBase(config.assetsBase ?? `/${outDir}`),
    basePath,
    dev: config.dev ?? true,
    manifest,
    logger: config.logger ?? defaultLogger,
  };
}
